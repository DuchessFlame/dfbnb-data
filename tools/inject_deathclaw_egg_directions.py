# Planned image paths
# ─────────────────────────────────────────────────────────────────────────────

def slug(s):
    """Lower-kebab a label the way the collectables image folders do."""
    s = (s or "").replace("'", "").replace("’", "")
    s = re.sub(r"[^A-Za-z0-9]+", "-", s).strip("-").lower()
    return re.sub(r"-{2,}", "-", s)


def plan_path(region, marker, label, kind):
    """kind: 'map' (image_top) or 'item' (image_bottom)."""
    return "%s/%s-%s-%s-%s.avif" % (
        IMG_BASE, slug(region), slug(marker), slug(label), kind
    )


def marker_map_path(region, marker):
    """One Pip-Boy map shot per MARKER (multi-spawn markers)."""
    return "%s/%s-%s-map.avif" % (IMG_BASE, slug(region), slug(marker))


def _have(path):
    """True if the converted AVIF for this site path is staged locally."""
    return bool(path) and os.path.exists(
        os.path.join(AVIF_DIR, os.path.basename(path))
    )


def set_slot(obj, field, path, hits):
    """Point `field` at `path` if the AVIF exists, else park it in _planned."""
    planned = field + "_planned"
    if _have(path):
        obj[field] = path
        obj.pop(planned, None)
        hits["live"] += 1
    else:
        obj[field] = ""
        obj[planned] = path
        hits["planned"] += 1


# ─────────────────────────────────────────────────────────────────────────────

def apply(path):
    if not os.path.exists(path):
        return None
    with open(path, encoding="utf-8") as fh:
        d = json.load(fh)

    hits = {"marker": [], "spawn": [], "planned": 0, "live": 0, "missing": []}

    for reg in d.get("regions", []):
        region = reg.get("region", "")
        for loc in reg.get("locations", []):
            mk = loc.get("marker", "")
            spawns = loc.get("spawns") or []

            # Walk order + renumbered labels BEFORE anything reads a label.
            spawns = reorder_and_relabel(loc)

            # Marker-level "Getting there" (multi-spawn markers only).
            if mk in MARKER_DIRECTIONS and len(spawns) > 1:
                loc["directions"] = MARKER_DIRECTIONS[mk]
                hits["marker"].append(mk)

            for sp in spawns:
                ref = (sp.get("ref") or "").upper()
                label = sp.get("label") or "spawn"

                if ref in SPAWN_DIRECTIONS:
                    sp["directions"] = SPAWN_DIRECTIONS[ref]
                    hits["spawn"].append("%s / %s" % (mk, label))
                else:
                    hits["missing"].append("%s / %s (%s)" % (mk, label, ref))

                # Photos are shot as ONE Pip-Boy map per marker plus one
                # in-world shot per spawn, so only single-spawn markers get a
                # per-spawn map slot — there the marker and the spawn are the
                # same place. Multi-spawn markers carry the map at marker level.
                if len(spawns) == 1:
                    set_slot(sp, "image_top", plan_path(region, mk, label, "map"), hits)
                else:
                    sp["image_top"] = ""
                    sp.pop("image_top_planned", None)
                set_slot(sp, "image_bottom", plan_path(region, mk, label, "item"), hits)

            # Marker-level map shot (multi-spawn markers only).
            if len(spawns) > 1:
                set_slot(loc, "image_top", marker_map_path(region, mk), hits)
            else:
                loc["image_top"] = ""
                loc.pop("image_top_planned", None)
            loc["image_bottom"] = ""
            loc.pop("image_bottom_planned", None)

            # Single-spawn markers render via loc.directions || spawn.directions.
            # Keep the marker field clear so the spawn text is what shows.
            if len(spawns) == 1 and mk not in MARKER_DIRECTIONS:
                loc["directions"] = loc.get("directions") or ""

    with open(path, "w", encoding="utf-8") as fh:
        json.dump(d, fh, ensure_ascii=False, indent=1)
    return hits


