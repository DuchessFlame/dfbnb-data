# label stem per source_type, used when renumbering
TYPE_LABEL = {"direct": "Deathclaw Egg", "nest": "Deathclaw Nest"}


def reorder_and_relabel(loc):
    """Sort a marker's spawns into walk order and renumber the labels."""
    spawns = loc.get("spawns") or []
    order = SPAWN_ORDER.get(loc.get("marker", ""))
    if order and len(spawns) > 1:
        rank = {r.upper(): i for i, r in enumerate(order)}
        spawns.sort(key=lambda s: rank.get((s.get("ref") or "").upper(), 999))
    # renumber within each source_type, in the (new) array order
    counts = {}
    for s in spawns:
        counts[s.get("source_type")] = counts.get(s.get("source_type"), 0) + 1
    seen = {}
    for s in spawns:
        st = s.get("source_type")
        stem = TYPE_LABEL.get(st) or (s.get("label") or "Spawn").split(" #")[0]
        seen[st] = seen.get(st, 0) + 1
        s["label"] = stem if counts.get(st, 0) == 1 else "%s #%d" % (stem, seen[st])
    loc["spawns"] = spawns
    # keep refs[] in step with the spawn order
    if spawns:
        loc["refs"] = [s.get("ref") for s in spawns if s.get("ref")]
    return spawns


