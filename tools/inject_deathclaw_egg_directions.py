# Walk order
#
# The build sorts a marker's spawns by (source_type, ref), which is stable but
# arbitrary on the ground — at Dino Peaks it put the Hole 3 nest fourth. The
# photographs are numbered in WALK order, and so are the directions above
# ("Nest 1 of 6"), so the JSON is re-sorted to match and the labels renumbered
# from the new positions. Ref -> text/photo bindings are unaffected: everything
# is keyed by ref, and the label is regenerated, never used as a key.
#
